#pragma once

#include <functional>

namespace baniphelper::core {

/// 把一个动作交给主线程执行。
///
/// 用途：平台实现常在别的线程（或别的进程的通知）下调回上层，而上层尤其是界面
/// 只能在主线程动。把这件事收在一个地方，两个后端才不会各自解释一遍
/// 「什么时候算在主线程上」。
///
/// 两条语义：
///
/// - 有事件循环时**排队投递**，不在调用者的栈上直接执行。统一成投递之后，
///   「发信号」这个动作不会被回调里的代码意外打断，行为也更容易预料；
/// - **没有事件循环时直接执行**。那时候不存在「主线程」这回事，
///   直接调用是唯一还有意义的选择，也好过把动作丢掉。
void runOnMainThread(std::function<void()> action);

}  // namespace baniphelper::core
